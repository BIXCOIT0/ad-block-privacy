"""Render the policy's limited Markdown subset as escaped, semantic static HTML."""
from pathlib import Path
import argparse, hashlib, html, re
ROOT = Path(__file__).resolve().parent.parent

def inline(text):
    pattern = re.compile(r'\[([^\]]+)\]\(([^\s)]+)\)|`([^`]+)`|https?://[^\s<>]+')
    output, at = [], 0
    for m in pattern.finditer(text):
        output.append(html.escape(text[at:m.start()]))
        if m[3] is not None:
            output.append('<code>' + html.escape(m[3]) + '</code>')
        else:
            label, url = (m[1], m[2]) if m[1] is not None else (m[0], m[0])
            suffix = ''
            if m[1] is None:
                url = url.rstrip('.,;!')
                suffix = m[0][len(url):]
                label = url
            if url.startswith(('https://', 'http://')) or url in ('PRIVACY.md', 'PRIVACY.en.md'):
                output.append('<a href="' + html.escape(url, quote=True) + '">' + html.escape(label) + '</a>')
            else:
                output.append(html.escape(m[0]))
            output.append(html.escape(suffix))
        at = m.end()
    return ''.join(output) + html.escape(text[at:])

def section(text, lang, ident):
    parts, toc, paragraph, count = [], [], [], 0
    def flush():
        if paragraph:
            parts.append('<p>' + inline(' '.join(paragraph)) + '</p>')
            paragraph.clear()
    for line in text.splitlines():
        match = re.match(r'^(#{1,3}) (.+)$', line)
        if match:
            flush(); count += 1
            level, title, anchor = min(4, len(match[1]) + 1), match[2], f'{ident}-section-{count}'
            parts.append(f'<h{level} id="{anchor}">{inline(title)}</h{level}>')
            if len(match[1]) == 2:
                toc.append(f'<li><a href="#{anchor}">{html.escape(title)}</a></li>')
        elif not line.strip():
            flush()
        else:
            paragraph.append(line)
    flush()
    label = 'Índice' if ident == 'pt' else 'Contents'
    return f'<section id="{ident}" lang="{lang}" aria-labelledby="{ident}-section-1"><nav aria-label="{label}"><ul>'+''.join(toc)+'</ul></nav>'+''.join(parts)+'</section>'

def render(root=ROOT):
    policies = [(root / 'PRIVACY.md').read_text(), (root / 'PRIVACY.en.md').read_text()]
    digest = hashlib.sha256('\0'.join(policies).encode()).hexdigest()
    return '''<!doctype html>
<!-- Generated by scripts/render_privacy.py; edit PRIVACY.md / PRIVACY.en.md. -->
<html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Privacidade / Privacy — PapaAnúncio</title><style>
:root{color-scheme:light dark;font-family:system-ui,sans-serif}*{box-sizing:border-box}body{max-width:960px;margin:0 auto;padding:24px 20px;font-size:16px;line-height:1.7}a{color:LinkText;overflow-wrap:anywhere}p,code,h1,h2,h3{overflow-wrap:anywhere}h2,h3{line-height:1.3;scroll-margin-top:16px}nav ul{padding-left:24px}.languages{display:flex;flex-wrap:wrap;gap:24px;padding:16px 0}section{border-top:1px solid GrayText;margin-top:32px;padding-top:16px}:focus-visible{outline:3px solid Highlight;outline-offset:3px}.skip{position:absolute;left:-10000px}.skip:focus{position:static}code{font-size:.95em}
</style></head><body><a class="skip" href="#content">Ir para o conteúdo / Skip to content</a><header><h1>Privacidade / Privacy</h1><nav class="languages" aria-label="Idioma / Language"><a href="#pt" lang="pt-BR">Português</a><a href="#en" lang="en">English</a></nav></header><main id="content" tabindex="-1">
''' + section(policies[0], 'pt-BR', 'pt') + '\n' + section(policies[1], 'en', 'en') + f'\n</main><!-- sources-sha256:{digest} --></body></html>\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    target = ROOT / 'index.html'; expected = render()
    if args.check:
        if target.read_text() != expected: raise SystemExit('index.html differs from policy sources; run python3 scripts/render_privacy.py')
        print('PASS generated HTML matches policy sources')
    else:
        target.write_text(expected)
